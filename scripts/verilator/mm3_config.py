#!/usr/bin/env python3
"""Generate integer C/SV constants and synthesizable ROMs; no model execution."""
import argparse,decimal,hashlib,json,pathlib,re
ROOT=pathlib.Path(__file__).resolve().parents[2]
p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
header=ROOT/'vsrc/soc/mm3/mm3_config.h';text=header.read_text()
c={k:int(v) for k,v in re.findall(r'^#define (MM3_\w+) (\d+)\s*$',text,re.M)}
def require(ok,msg):
 if not ok:raise SystemExit(msg)
require(c['MM3_GEMV_LANES'] in (1,2,4,8,16,32),'GEMV lanes must divide 32')
require(c['MM3_VEC_LANES'] in (1,2,4,8,16),'vector lanes must be a power of two <=16')
require(all(1<=c[x]<=16 for x in ('MM3_GEMM_ROWS','MM3_GEMM_COLS')),'array rows/columns must be 1..16')
require(4<=c['MM3_RSQRT_LUT_BITS']<=10 and 1<=c['MM3_RSQRT_ITERS']<=3,'unsupported rsqrt tuning')
require(c['MM3_MAX_VECTOR']>=2432 and 768<=c['MM3_NORM_MAX_LEN']<=c['MM3_MAX_VECTOR'],'capacity below model dimensions')
require(4<=c['MM3_SEQ_CAP']<=2048,'KV capacity must be 4..2048')
require(c['MM3_TEST_POSITION']==0 and c['MM3_TEST_LAYER']==0,'v1 layer fixture is first layer, position zero')
require(2<=c['MM3_TEST_ATTN_LEN']<=c['MM3_SEQ_CAP'],'attention fixture exceeds cache')
require(c['MM3_TEST_TOKEN_ID']<6400,'invalid token')
require(32*1024*1024<=c['MM3_DDR_BYTES']<=512*1024*1024,'DDR capacity must cover fixture windows')
require(1<=c['MM3_MAX_COMMANDS']<=512,'command list overlaps fixed memory windows')
require(c['MM3_GEMM_MAX_M']>=2 and c['MM3_GEMM_MAX_N']>=max(96,c['MM3_SEQ_CAP']) and c['MM3_GEMM_MAX_K']>=max(96,c['MM3_SEQ_CAP']),'GEMM capacities must cover head dimension and context')
require([c[k] for k in ('MM3_HIDDEN_SIZE','MM3_FFN_SIZE','MM3_HEAD_DIM','MM3_QUERY_HEADS','MM3_KV_HEADS','MM3_VOCAB_SIZE')]==[768,2432,96,8,4,6400],'model dimensions differ from locked assets')
decimal.getcontext().prec=90;D=decimal.Decimal;B=c['MM3_RSQRT_LUT_BITS'];lut=[]
for parity in range(2):
 for i in range(1<<B):
  t=(1+(D(i)+D('0.5'))/D(1<<B))*D(1<<parity)
  lut.append(int((D(1<<31)/t.sqrt()).to_integral_value(rounding=decimal.ROUND_HALF_EVEN)))
recip=[0]+[int((D(1<<48)/n).to_integral_value(rounding=decimal.ROUND_HALF_EVEN)) for n in range(1,c['MM3_NORM_MAX_LEN']+1)]
def emit(path,s):
 path=ROOT/path
 if args.check:require(path.exists() and path.read_text()==s,'stale generated file: '+str(path))
 else:path.parent.mkdir(parents=True,exist_ok=True);path.write_text(s)
sv='// Generated by mm3_config.py; edit mm3_config.h instead.\npackage mm3_config_pkg;\n'+''.join(f'    localparam int unsigned {k} = {v};\n' for k,v in c.items())+'endpackage\n'
emit(pathlib.Path('vsrc/soc/mm3/common/mm3_config_pkg.sv'),sv)
rom='// Module: mm3_tables_pkg\n// Description: Generated constant ROMs; no simulation-only initialization.\npackage mm3_tables_pkg;\n'
for name,table,width in [('rsqrt_seed',lut,32),('length_recip',recip,64)]:
 rom+=f'    function automatic logic [{width-1}:0] {name}(input int unsigned index);\n        case(index)\n'
 rom+=''.join(f"            {i}: return {width}'d{v};\n" for i,v in enumerate(table))
 rom+="            default: return '0;\n        endcase\n    endfunction\n"
rom+='endpackage\n';emit(pathlib.Path('vsrc/soc/mm3/common/mm3_tables_pkg.sv'),rom)
ch='/* Generated constants; arithmetic is integer-only at runtime. */\n#ifndef MM3_TABLES_H\n#define MM3_TABLES_H\n#include <stdint.h>\n'
for name,table in [('rsqrt_seed',lut),('length_recip',recip)]:
 ch+=f'static const uint64_t mm3_{name}[{len(table)}]={{\n'+''.join(f' UINT64_C({v}),\n' for v in table)+'};\n'
ch+='#endif\n';emit(pathlib.Path('software/minimind3/operators/mm3_tables.h'),ch)
out=ROOT/'build/mm3-ops/config';out.mkdir(parents=True,exist_ok=True)
(out/'config.json').write_text(json.dumps({'config':c,'sha256':hashlib.sha256(text.encode()).hexdigest()},indent=2)+'\n')
print('CONFIG_CHECK' if args.check else 'CONFIG_GENERATED',hashlib.sha256(text.encode()).hexdigest()[:16])
